#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const runtimeAssetPaths = [
  'public/worklets/kessho-core-product.worklet.js',
  'public/worklets/kessho_core.wasm',
];

const hash = createHash('sha256');

for (const relativePath of runtimeAssetPaths) {
  const bytes = await readFile(path.join(rootDir, relativePath));
  hash.update(relativePath);
  hash.update('\0');
  hash.update(bytes);
  hash.update('\0');
}

const version = hash.digest('hex').slice(0, 16);
const outDir = path.join(rootDir, 'src/audio/generated');
const outFile = path.join(outDir, 'coreProductRuntimeAssetVersion.ts');

await mkdir(outDir, { recursive: true });
await writeFile(
  outFile,
  `// Generated by scripts/generate-core-product-runtime-asset-version.mjs. Do not edit by hand.\n` +
    `export const CORE_PRODUCT_RUNTIME_ASSET_VERSION = '${version}';\n`,
);

console.log(`Generated ${path.relative(rootDir, outFile)} = ${version}`);
