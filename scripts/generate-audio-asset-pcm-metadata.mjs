#!/usr/bin/env node
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const samplesRoot = path.join(root, 'public/samples');
const output = path.join(root, 'src/audio/generated/audioAssetPcmMetadata.ts');

function readU64LE(bytes, offset) {
  return bytes.readBigUInt64LE(offset);
}

function inspectOggVorbis(bytes, relativePath) {
  let offset = 0;
  let channels = 0;
  let sampleRate = 0;
  let finalFrame = 0n;
  while (offset + 27 <= bytes.length) {
    if (bytes.toString('ascii', offset, offset + 4) !== 'OggS') {
      throw new Error(`Invalid Ogg page in ${relativePath} at ${offset}`);
    }
    const segmentCount = bytes[offset + 26];
    if (offset + 27 + segmentCount > bytes.length) throw new Error(`Truncated Ogg lacing table in ${relativePath}`);
    let bodyBytes = 0;
    for (let index = 0; index < segmentCount; index += 1) bodyBytes += bytes[offset + 27 + index];
    const bodyOffset = offset + 27 + segmentCount;
    if (bodyOffset + bodyBytes > bytes.length) throw new Error(`Truncated Ogg page in ${relativePath}`);
    const granule = readU64LE(bytes, offset + 6);
    if (granule !== 0xffffffffffffffffn) finalFrame = granule;
    if (channels === 0) {
      const marker = bytes.indexOf(Buffer.from([1, 0x76, 0x6f, 0x72, 0x62, 0x69, 0x73]), bodyOffset);
      if (marker >= bodyOffset && marker + 16 <= bodyOffset + bodyBytes) {
        channels = bytes[marker + 11];
        sampleRate = bytes.readUInt32LE(marker + 12);
      }
    }
    offset = bodyOffset + bodyBytes;
  }
  if (channels < 1 || sampleRate < 1 || finalFrame < 1n) throw new Error(`Missing Vorbis PCM metadata in ${relativePath}`);
  if (finalFrame > BigInt(Number.MAX_SAFE_INTEGER)) throw new Error(`PCM frame count exceeds safe integer in ${relativePath}`);
  return { channels, sampleRate, frames: Number(finalFrame) };
}

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(absolute));
    else if (entry.isFile() && entry.name.toLowerCase().endsWith('.ogg')) files.push(absolute);
  }
  return files;
}

const rows = {};
for (const absolute of (await walk(samplesRoot)).sort()) {
  const assetPath = path.relative(samplesRoot, absolute).split(path.sep).join('/');
  rows[assetPath] = inspectOggVorbis(await readFile(absolute), assetPath);
}

await writeFile(output,
  '// Generated by scripts/generate-audio-asset-pcm-metadata.mjs. Do not edit by hand.\n' +
  `export const AUDIO_ASSET_PCM_METADATA = ${JSON.stringify(rows, null, 2)} as const;\n`);
console.log(`Generated ${path.relative(root, output)} (${Object.keys(rows).length} assets)`);
