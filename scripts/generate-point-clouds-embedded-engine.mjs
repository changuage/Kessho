#!/usr/bin/env node

import { build, transform } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(new URL('..', import.meta.url).pathname);
const outputDir = resolve(root, 'point-clouds/shared/embedded');
const engineEntry = resolve(outputDir, 'kessho-engine-entry.tsx');
const engineOutput = resolve(outputDir, 'kessho-engine.iife.js');
const assetOutput = resolve(outputDir, 'kessho-product-core-assets.js');
const engineDocumentOutput = resolve(outputDir, 'kessho-engine.html');
const workletPath = resolve(root, 'public/worklets/kessho-core-product.worklet.js');
const wasmPath = resolve(root, 'public/worklets/kessho_core.wasm');
const stringWavesSamplePath = resolve(root, 'public/samples/Ghetary-Waves-Rocks_120s_m_441_cl-normalized.ogg');
const bridgePath = resolve(root, 'point-clouds/shared/kessho-site-bridge.js');
const pointCloudPagePaths = [
  resolve(root, 'point-clouds/index.html'),
  resolve(root, 'point-clouds/alternative-a/index.html'),
  resolve(root, 'point-clouds/alternative-b/index.html'),
];
// Keep the regular Vite bundled fallback and the direct-file Point Clouds
// artifact byte-identical. The public asset is the canonical materialized V2
// SavedPreset snapshot; generation only embeds a copy for file:// playback.
const stringWavesPresetPath = resolve(root, 'public/presets/StringWaves.json');

function readEmbeddedBuildEnv() {
  // The direct-file engine carries its own preset and sample bytes. Keep all
  // cloud/public credentials absent from this artifact even when the working
  // tree has a developer .env file; the regular Vite build still reads those
  // values through its normal environment loading.
  return {
    BASE_URL: '/',
    DEV: false,
    MODE: 'production',
    PROD: true,
    SSR: false,
    VITE_SUPABASE_URL: '',
    VITE_SUPABASE_ANON_KEY: '',
    NEXT_PUBLIC_SUPABASE_URL: '',
    NEXT_PUBLIC_SUPABASE_ANON_KEY: '',
    VITE_KESSHO_ENABLE_GRAPH_CAPTURE: '',
  };
}

function makeAssetScript(workletSource, wasmBytes, stringWavesSampleBytes, stringWavesPreset) {
  const workletBase64 = Buffer.from(workletSource, 'utf8').toString('base64');
  const wasmBase64 = wasmBytes.toString('base64');
  const stringWavesSampleBase64 = stringWavesSampleBytes.toString('base64');
  return `/* Generated by scripts/generate-point-clouds-embedded-engine.mjs. Do not edit. */
(function installEmbeddedProductCoreAssets(global) {
  'use strict';
  if (!global || typeof global.atob !== 'function') {
    throw new Error('Embedded Product Core assets require atob support.');
  }
  const workletSource = ${JSON.stringify(workletSource)};
  const workletBase64 = ${JSON.stringify(workletBase64)};
  const wasmBase64 = ${JSON.stringify(wasmBase64)};
  const embeddedSampleBase64 = ${JSON.stringify(stringWavesSampleBase64)};
  const embeddedStringWavesPreset = ${JSON.stringify(stringWavesPreset)};
  const wasmBinaryString = global.atob(wasmBase64);
  const wasmBytes = new Uint8Array(wasmBinaryString.length);
  for (let index = 0; index < wasmBinaryString.length; index += 1) {
    wasmBytes[index] = wasmBinaryString.charCodeAt(index);
  }
  const wasmBinary = wasmBytes.buffer;
  const workletDataUrl = 'data:text/javascript;base64,' + workletBase64;
  const wasmDataUrl = 'data:application/wasm;base64,' + wasmBase64;
  // HTTP/srcdoc playback can use efficient blob URLs, while file:// and
  // opaque origins select the data URLs above in CoreProductRuntime. Keep the
  // data forms available even when Blob URL support is absent altogether.
  const canCreateBlobUrls = typeof global.Blob === 'function'
    && typeof global.URL?.createObjectURL === 'function';
  const workletUrl = canCreateBlobUrls
    ? global.URL.createObjectURL(new global.Blob([workletSource], {
      type: 'application/javascript',
    }))
    : workletDataUrl;
  const wasmUrl = canCreateBlobUrls
    ? global.URL.createObjectURL(new global.Blob([wasmBinary], {
      type: 'application/wasm',
    }))
    : wasmDataUrl;
  const assetBaseUrl = 'https://point-clouds.invalid/';
  const isFileOrOpaqueOrigin = () => (
    global.location?.protocol === 'file:' || global.location?.origin === 'null'
  );
  const sampleBinaryString = global.atob(embeddedSampleBase64);
  const sampleBytes = new Uint8Array(sampleBinaryString.length);
  for (let index = 0; index < sampleBinaryString.length; index += 1) {
    sampleBytes[index] = sampleBinaryString.charCodeAt(index);
  }
  const originalFetch = typeof global.fetch === 'function' ? global.fetch.bind(global) : null;
  if (originalFetch && typeof global.Response === 'function') {
    global.fetch = (input, init) => {
      const inputUrl = typeof input === 'string' ? input : input?.url;
      let parsedUrl = null;
      try { parsedUrl = new global.URL(inputUrl, global.location?.href); } catch { parsedUrl = null; }
      // The normal app boot asks the optional bundled-preset loaders for this
      // manifest. A direct file has no HTTP public root, so answer that local
      // discovery request with an empty manifest and keep the rest of fetch
      // untouched. The embedded String Waves snapshot is provided below.
      if (
        isFileOrOpaqueOrigin()
        && (inputUrl === '/presets/manifest.json'
          || (parsedUrl?.protocol === 'file:' && parsedUrl.pathname === '/presets/manifest.json'))
      ) {
        return Promise.resolve(new global.Response(JSON.stringify({ files: [] }), {
          status: 200,
          headers: { 'Content-Type': 'application/json' },
        }));
      }
      if (
        isFileOrOpaqueOrigin()
        && (inputUrl?.startsWith?.('/presets/')
          || (parsedUrl?.protocol === 'file:' && parsedUrl.pathname?.startsWith('/presets/')))
        && (inputUrl?.endsWith?.('.json') || parsedUrl?.pathname?.endsWith('.json'))
      ) {
        // loadPresetsFromFolder probes a legacy fallback list after an empty
        // manifest. Return a quiet local 404 instead of letting file:// fetch
        // surface an unsupported-scheme console error for every candidate.
        return Promise.resolve(new global.Response('', { status: 404 }));
      }
      if (parsedUrl?.origin === assetBaseUrl.slice(0, -1)) {
        const path = parsedUrl.pathname.startsWith('/')
          ? parsedUrl.pathname.slice(1)
          : parsedUrl.pathname;
        if (path === 'samples/Ghetary-Waves-Rocks_120s_m_441_cl-normalized.ogg') {
          return Promise.resolve(new global.Response(sampleBytes.slice(), {
            status: 200,
            headers: { 'Content-Type': 'audio/ogg' },
          }));
        }
      }
      return originalFetch(input, init);
    };
  }
  global.__pointCloudsEmbeddedProductCoreAssets = Object.freeze({
    workletUrl,
    workletDataUrl,
    wasmUrl,
    wasmDataUrl,
    wasmBinary,
    ...(assetBaseUrl ? { assetBaseUrl } : {}),
  });
  global.__pointCloudsEmbeddedStringWavesPreset = embeddedStringWavesPreset;
})(typeof window !== 'undefined' ? window : globalThis);
`;
}

await mkdir(outputDir, { recursive: true });
const [workletSource, wasmBytes, stringWavesSampleBytes, stringWavesPresetSource] = await Promise.all([
  readFile(workletPath, 'utf8'),
  readFile(wasmPath),
  readFile(stringWavesSamplePath),
  readFile(stringWavesPresetPath, 'utf8'),
]);
const stringWavesPreset = JSON.parse(stringWavesPresetSource);
const embeddedBuildEnv = readEmbeddedBuildEnv();

await build({
  entryPoints: [engineEntry],
  outfile: engineOutput,
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  sourcemap: false,
  legalComments: 'none',
  treeShaking: true,
  loader: { '.css': 'empty' },
  define: {
    'import.meta.env': JSON.stringify(embeddedBuildEnv),
    'process.env.NODE_ENV': '"production"',
  },
  logLevel: 'warning',
});

await writeFile(assetOutput, makeAssetScript(workletSource, wasmBytes, stringWavesSampleBytes, stringWavesPreset));

// A regular file document is more portable than an opaque `about:srcdoc`
// frame on browsers that deny file:// subresources from an opaque origin.
// Keep the generated document tiny; the two classic scripts remain sibling
// files so direct-file opens do not need an 8 MiB data URL or a duplicate
// bridge bundle.
await writeFile(engineDocumentOutput, `<!doctype html>
<html><head><meta charset="utf-8"></head><body>
<div id="kessho-engine-root" aria-hidden="true" style="width:1px;height:1px;overflow:hidden"></div>
<script>window.__pointCloudsEmbeddedEngineMode = true;</script>
<script src="./kessho-product-core-assets.js"></script>
<script src="./kessho-engine.iife.js"></script>
</body></html>
`);

// Keep each standalone Point Clouds page usable even when a browser refuses
// the external shared bridge script in a file-origin page. The fallback is
// only evaluated when the external script did not install PointCloudsKessho;
// in the normal HTTP path it is a cheap guard and does not duplicate the
// bridge.
const bridgeSource = await readFile(bridgePath, 'utf8');
const { code: minifiedBridgeSource } = await transform(bridgeSource, {
  minify: true,
  target: 'es2020',
  legalComments: 'none',
});
const fallbackScript = `
    /* Generated by scripts/generate-point-clouds-embedded-engine.mjs. */
    if (!window.PointCloudsKessho) {
      ${minifiedBridgeSource.trim()}
    }
  `;
const fallbackMarker = /(<script data-point-clouds-bridge-fallback>)[\s\S]*?(<\/script>)/;
await Promise.all(pointCloudPagePaths.map(async (pagePath) => {
  const source = await readFile(pagePath, 'utf8');
  if (!fallbackMarker.test(source)) {
    throw new Error(`Missing Point Clouds bridge fallback marker in ${pagePath}`);
  }
  await writeFile(pagePath, source.replace(fallbackMarker, (_match, start, end) => `${start}${fallbackScript}${end}`));
}));

const engineSize = (await readFile(engineOutput)).byteLength;
const assetSize = (await readFile(assetOutput)).byteLength;
console.log(`Generated embedded Point Clouds Product Core assets (${engineSize} byte engine, ${assetSize} byte asset loader, engine document).`);
